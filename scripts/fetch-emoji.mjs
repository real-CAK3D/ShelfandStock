// Bundle Microsoft Fluent Emoji 3D (MIT) images for every emoji the app uses, so icons work
// offline. Run: node scripts/fetch-emoji.mjs   (re-run after adding foods/recipes with new emoji)
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'www');
const out = join(root, 'vendor', 'emoji');
const CDN = 'https://cdn.jsdelivr.net/npm/@lobehub/fluent-emoji-3d@1.1.0/assets/';
const RE = /\p{Extended_Pictographic}[️⃣]?(?:‍\p{Extended_Pictographic}️?)*/gu;
const SKIP = new Set(['©', '®', '™', '‼', '⁉', '↔', '↔️', '▶']);

const files = [];
const walk = d => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) { if (!p.includes('vendor')) walk(p); } else if (/\.(js|html|css)$/.test(f)) files.push(p); } };
walk(root);
const found = new Set();
for (const f of files) for (const m of readFileSync(f, 'utf8').matchAll(RE)) if (!SKIP.has(m[0])) found.add(m[0]);

const hex = e => [...e].map(c => c.codePointAt(0).toString(16)).join('-');
mkdirSync(out, { recursive: true });
const have = [], missing = [];
await Promise.all([...found].map(async e => {
  const tries = [hex(e), hex(e.replace(/️/g, '')), hex(e.replace(/️/g, '')) + '-fe0f'];
  for (const h of [...new Set(tries)]) {
    const file = join(out, h + '.webp');
    if (existsSync(file)) { have.push(h); return; }
    const r = await fetch(CDN + h + '.webp');
    if (r.ok) { writeFileSync(file, Buffer.from(await r.arrayBuffer())); have.push(h); return; }
  }
  missing.push(e);
}));
writeFileSync(join(out, 'index.js'), `// generated by scripts/fetch-emoji.mjs — Fluent Emoji 3D images bundled with the app\nexport const LOCAL = new Set(${JSON.stringify(have.sort())});\n`);
console.log(`bundled ${have.length} emoji, missing ${missing.length}: ${missing.join(' ')}`);
